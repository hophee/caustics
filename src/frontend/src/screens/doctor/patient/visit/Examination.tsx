export function Examination({ values, onChange }: { values: Record<string, string>; onChange: (v: Record<string, string>) => void }) {
  const set = (key: string, value: string) => onChange({ ...values, [key]: value });
  const height = Number(values["Рост, см"]); const weight = Number(values["Масса, кг"]);
  return <details className="card pad"><summary>Базовый осмотр · необязательно</summary>
    {Object.entries(groups).map(([group, fields]) => <fieldset key={group}><legend>{group}</legend><div className="visit-fields">
      {Object.entries(fields).map(([name, options]) => <label className="fld" key={name}>{name}
        {options.length ? <select className="inp" value={values[name] ?? ""} onChange={(e) => set(name, e.target.value)}>
          <option value="">Не оценено / не исследовано</option>{options.map((o) => <option key={o}>{o}</option>)}
        </select> : <input className="inp" value={values[name] ?? ""} onChange={(e) => set(name, e.target.value)} />}
      </label>)}
    </div></fieldset>)}
    {height > 0 && weight > 0 && <p>ИМТ: {(weight / (height / 100) ** 2).toFixed(1)}</p>}
    <label className="fld">Дополнительное описание<textarea className="inp" value={values.comment ?? ""} onChange={(e) => set("comment", e.target.value)} /></label>
  </details>;
}
