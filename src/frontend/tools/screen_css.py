"""Generate per-screen stylesheets from the approved canvas boards («Итерация 2»).

Each board = shared k.css / p.css + its own <style>. The board style is written against the root
(.k doctor, .p patient). In the app every screen's style is scoped as `.k.scr-<slug>` (or `.p.…`):
the shell adds `scr-<slug>` to the root while that screen (or dialog) is shown.
usage: python3 tools/screen_css.py   (run from src/frontend)
"""
import re
from pathlib import Path

BOARDS = Path("../../design/canvas/project")
OUT = Path("src/styles/screens")
DIALOGS = {"newpatient", "alert", "pickempty", "picksearch"}  # root = the scrim → `.dlg` overlay
SKIP = re.compile(r"^(A|B|C|T\d)-|^Main\.")


def slug(name: str) -> str:
    base = name.split(".")[0]
    for prefix, repl in (("I2-", ""), ("P-", "p-"), ("S-", "s-"), ("K-", "k-"), ("D-", "")):
        if base.startswith(prefix):
            base = repl + base[len(prefix):]
    return base.lower()


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    for board in sorted(BOARDS.glob("*.dc.html")):
        if SKIP.match(board.name):
            continue
        html = board.read_text(encoding="utf-8")
        style = re.search(r"<style>(.*?)</style>", html, re.S)
        root = re.search(r'<div class="([a-z]+)"', html[html.find("</helmet>"):]).group(1)
        css = style.group(1) if style else ""
        css = re.sub(r"/\*.*?\*/", "", css, flags=re.S)
        name = slug(board.name)
        css = re.sub(r"(^|\n)\s*body\{[^}]*\}", r"\1", css)
        css = re.sub(r"(^|\n)\s*a\{[^}]*\}a:hover\{[^}]*\}", r"\1", css)
        # a selector starting with the root class (".k{", ".ab .in", ".scrim,.x") → "&…" (the scoped root)
        css = re.sub(r"(^|[\n{},])(\s*)\." + root + r"(?=[\s{.:#\[>+~,])", r"\1\2&", css)
        head = f"/* Generated by tools/screen_css.py from design/canvas/project/{board.name}. Do not edit. */\n"
        scope = "dlg" if name in DIALOGS else root
        (OUT / f"{name}.css").write_text(head + f".{scope}.scr-{name}{{\n{css.strip()}\n}}\n", encoding="utf-8")
        print(f"{name:14} .{root} {len(css):6}")
    index = sorted(f.name for f in OUT.glob("*.css"))
    Path("src/styles/screens.css").write_text(
        "/* Generated by tools/screen_css.py. */\n" + "".join(f'@import "./screens/{n}";\n' for n in index), encoding="utf-8"
    )


main()
